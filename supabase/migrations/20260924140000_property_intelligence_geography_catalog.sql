-- Property Intelligence: nationwide geography catalog (Slice 1 of the
-- nationwide multi-state ingestion architecture; see
-- docs/PROPERTY_INTELLIGENCE_PORT_PLAN.md). Ported from
-- property-intelligence-app's supabase/migrations/20260819224113_nationwide_property_model.sql
-- (jurisdictions table) and 20260820231238_add_geography_catalog_imports.sql
-- (geography_catalog_imports / geography_catalog_entries), trimmed to the
-- geography-only slice: no source_definitions, source_candidates,
-- properties, auction_events, or any other table from the source's much
-- larger nationwide model. Those belong to later slices (source adapters,
-- the ingestion orchestrator) once approved.
--
-- Status: schema + reference-data tables only, not applied to the live
-- Supabase project (PRODUCTION_PROJECT_REF) from this session -- migration
-- file only, matching every prior Property Intelligence phase in this repo.
-- Nothing in this repo writes to these tables yet: the import logic in
-- src/lib/property-intelligence/nationwide-geography-catalog.ts is dormant
-- library code, not wired to any cron, server function, or route.
--
-- Schema-qualification judgment call: this repo's existing Property
-- Intelligence tables (property_reports, property_owner_documents,
-- property_deal_scenarios, etc.) all live in `public`, matching every other
-- table in this repo -- there is no existing precedent for a non-public
-- schema here (the only non-"public"-named migration files are Lovable's
-- own UUID-suffixed autogenerated filenames, which still create public
-- objects). The source app uses `property_core` / `property_ingest` /
-- `property_api` precisely because it layers a public-facing API schema
-- (`property_api`) in front of tables it locks away from every client role,
-- including `authenticated` -- reads only ever go through `property_api`
-- views. This repo has no such API-schema layer, and the task instructions
-- ask for straightforward authenticated-read / admin-or-service-role-write
-- access, which a `public`-schema table with RLS already gives us cleanly.
--
-- We still port `property_core` / `property_ingest` (not `property_api`,
-- which is out of scope for this slice and everything in it besides
-- jurisdictions/geography) as real Postgres schemas rather than collapsing
-- them into `public`, because: (a) later slices (source adapters, the
-- ingestion orchestrator, health monitoring) will add many more tables
-- under these same two schemas, exactly mirroring the source app's split
-- between durable geography/property identity (`property_core`) and
-- ingestion-pipeline bookkeeping (`property_ingest`) -- starting that split
-- now avoids a rename later; and (b) it keeps this subsystem's tables
-- clearly out of the `public` schema this repo's existing product tables
-- live in, which matters once source adapters start writing large ingestion
-- volumes. Supabase's Data API only exposes schemas explicitly added to it
-- (see the source's own migration header, "Add `property_api` to the Data
-- API"), so simply creating `property_core`/`property_ingest` here does not
-- expose them to REST/PostgREST callers by itself; PostgREST access is not
-- requested or granted in this migration.
--
-- RLS judgment call: the source app locks property_core/property_ingest
-- entirely -- `revoke all ... from public, anon, authenticated` with no
-- policies at all, because every client read goes through property_api
-- views instead. That does not fit this repo (no property_api layer here),
-- and the task instructions call these "reference/catalog tables, not user
-- data" that should be readable by authenticated users, with writes
-- restricted to admin/service-role. So: `authenticated` gets a blanket
-- SELECT policy on all three tables, `service_role` gets full access (as
-- with every other table in this repo), and INSERT/UPDATE/DELETE from an
-- ordinary authenticated session require `public.has_role(auth.uid(),
-- 'admin')`, matching the admin/moderator-gated write pattern already used
-- for public.property_owner_documents.

begin;

create schema if not exists property_core;
create schema if not exists property_ingest;

revoke all on schema property_core from public, anon, authenticated;
revoke all on schema property_ingest from public, anon, authenticated;
grant usage on schema property_core, property_ingest to authenticated, service_role;

-- property_core.jurisdictions ------------------------------------------
-- Canonical federal geography identity: states/DC and counties/county
-- equivalents today; municipality/district/agency_area rows are reserved
-- for later slices, matching the source's jurisdiction_type contract.
create table property_core.jurisdictions (
  id uuid primary key default gen_random_uuid(),
  parent_id uuid references property_core.jurisdictions (id),
  jurisdiction_type text not null check (
    jurisdiction_type in ('state', 'county_equivalent', 'municipality', 'district', 'agency_area')
  ),
  name text not null,
  legal_name text,
  state_code text check (state_code is null or state_code ~ '^[A-Z]{2}$'),
  state_fips text check (state_fips is null or state_fips ~ '^[0-9]{2}$'),
  county_fips text check (county_fips is null or county_fips ~ '^[0-9]{5}$'),
  place_fips text check (place_fips is null or place_fips ~ '^[0-9]{5}$'),
  gnis_id text,
  timezone text,
  active_from date,
  active_to date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (active_to is null or active_from is null or active_to >= active_from)
);

create unique index jurisdictions_scope_uidx
  on property_core.jurisdictions (
    jurisdiction_type,
    coalesce(state_fips, ''),
    coalesce(county_fips, ''),
    coalesce(place_fips, ''),
    lower(name)
  );

-- Federal geography codes are identities, not descriptive attributes. These
-- indexes prevent a misspelled name from creating a second state or county.
create unique index jurisdictions_state_code_uidx
  on property_core.jurisdictions (state_code)
  where jurisdiction_type = 'state';

create unique index jurisdictions_state_fips_uidx
  on property_core.jurisdictions (state_fips)
  where jurisdiction_type = 'state';

create unique index jurisdictions_county_fips_uidx
  on property_core.jurisdictions (county_fips)
  where jurisdiction_type = 'county_equivalent';

create index jurisdictions_parent_idx on property_core.jurisdictions (parent_id);

revoke all on property_core.jurisdictions from public, anon, authenticated;
grant select, insert, update, delete on property_core.jurisdictions to authenticated;
grant all on property_core.jurisdictions to service_role;
alter table property_core.jurisdictions enable row level security;
alter table property_core.jurisdictions force row level security;

create policy jurisdictions_read
  on property_core.jurisdictions for select to authenticated
  using (true);

create policy jurisdictions_admin_write
  on property_core.jurisdictions for insert to authenticated
  with check (public.has_role(auth.uid(), 'admin'));

create policy jurisdictions_admin_update
  on property_core.jurisdictions for update to authenticated
  using (public.has_role(auth.uid(), 'admin'))
  with check (public.has_role(auth.uid(), 'admin'));

create policy jurisdictions_admin_delete
  on property_core.jurisdictions for delete to authenticated
  using (public.has_role(auth.uid(), 'admin'));

-- property_ingest.geography_catalog_imports / geography_catalog_entries -
-- Append-only ledger of every geography catalog version imported into
-- property_core.jurisdictions, and the exact, per-row fingerprinted
-- contents of each import, ported from the source's
-- add_geography_catalog_imports.sql migration (same columns/constraints).
create table property_ingest.geography_catalog_imports (
  id uuid primary key default gen_random_uuid(),
  catalog_key text not null check (catalog_key ~ '^[a-z0-9]+(?:_[a-z0-9]+)*$'),
  catalog_version integer not null check (catalog_version > 0),
  catalog_fingerprint text not null check (catalog_fingerprint ~ '^[0-9a-f]{64}$'),
  gazetteer_vintage integer not null check (gazetteer_vintage between 2000 and 9999),
  scope text not null check (btrim(scope) <> ''),
  source_url text not null check (source_url ~ '^https://'),
  source_archive_sha256 text not null check (source_archive_sha256 ~ '^[0-9a-f]{64}$'),
  source_entry_name text not null check (btrim(source_entry_name) <> ''),
  source_entry_sha256 text not null check (source_entry_sha256 ~ '^[0-9a-f]{64}$'),
  source_row_count integer not null check (source_row_count > 0),
  included_row_count integer not null check (
    included_row_count > 0 and included_row_count <= source_row_count
  ),
  state_equivalent_count integer not null check (state_equivalent_count between 1 and 99),
  excluded_rows jsonb not null check (jsonb_typeof(excluded_rows) = 'array'),
  imported_by text not null check (btrim(imported_by) <> ''),
  imported_at timestamptz not null,
  created_at timestamptz not null default now(),
  unique (catalog_key, catalog_version)
);

create table property_ingest.geography_catalog_entries (
  catalog_import_id uuid not null
    references property_ingest.geography_catalog_imports (id),
  entry_index integer not null check (entry_index >= 0),
  jurisdiction_id uuid not null references property_core.jurisdictions (id),
  state_code text not null check (state_code ~ '^[A-Z]{2}$'),
  state_fips text not null check (state_fips ~ '^[0-9]{2}$'),
  state_name text not null check (btrim(state_name) <> ''),
  county_fips text not null check (county_fips ~ '^[0-9]{5}$'),
  county_name text not null check (btrim(county_name) <> ''),
  county_legal_name text not null check (btrim(county_legal_name) <> ''),
  county_equivalent_type text not null check (
    county_equivalent_type in (
      'borough', 'census_area', 'city_and_borough', 'county', 'district',
      'independent_city', 'municipality', 'parish', 'planning_region'
    )
  ),
  ansi_code text not null check (ansi_code ~ '^[0-9]{8}$'),
  entry_fingerprint text not null check (entry_fingerprint ~ '^[0-9a-f]{64}$'),
  created_at timestamptz not null default now(),
  primary key (catalog_import_id, entry_index),
  unique (catalog_import_id, jurisdiction_id),
  unique (catalog_import_id, county_fips),
  unique (catalog_import_id, ansi_code)
);

create index geography_catalog_entries_jurisdiction_idx
  on property_ingest.geography_catalog_entries (jurisdiction_id, catalog_import_id);

create index geography_catalog_entries_state_idx
  on property_ingest.geography_catalog_entries (state_code, catalog_import_id);

-- Ledger integrity: an import row and its entries must completely agree
-- with each other and with the canonical property_core.jurisdictions rows
-- they reference, or the whole transaction fails closed. Ported verbatim
-- (logic unchanged) from the source's validate_geography_catalog_import.
create or replace function property_ingest.validate_geography_catalog_import(import_id uuid)
returns void
language plpgsql
set search_path = pg_catalog, property_core, property_ingest
as $$
declare
  expected_count integer;
  expected_state_count integer;
  observed_count integer;
  observed_state_count integer;
  minimum_index integer;
  maximum_index integer;
  mismatch_count integer;
begin
  select included_row_count, state_equivalent_count
  into strict expected_count, expected_state_count
  from property_ingest.geography_catalog_imports
  where id = import_id;

  select count(*)::integer, count(distinct state_code)::integer,
    min(entry_index), max(entry_index)
  into observed_count, observed_state_count, minimum_index, maximum_index
  from property_ingest.geography_catalog_entries
  where catalog_import_id = import_id;

  if observed_count <> expected_count
    or observed_state_count <> expected_state_count
    or minimum_index is distinct from 0
    or maximum_index is distinct from expected_count - 1 then
    raise exception 'geography catalog entries must completely match their declared row and state counts';
  end if;

  select count(*)::integer
  into mismatch_count
  from property_ingest.geography_catalog_entries entry
  join property_core.jurisdictions county on county.id = entry.jurisdiction_id
  left join property_core.jurisdictions state on state.id = county.parent_id
  where entry.catalog_import_id = import_id
    and (
      county.jurisdiction_type <> 'county_equivalent'
      or county.state_code is distinct from entry.state_code
      or county.state_fips is distinct from entry.state_fips
      or county.county_fips is distinct from entry.county_fips
      or county.name is distinct from entry.county_name
      or county.legal_name is distinct from entry.county_legal_name
      or state.id is null
      or state.jurisdiction_type <> 'state'
      or state.state_code is distinct from entry.state_code
      or state.state_fips is distinct from entry.state_fips
      or state.name is distinct from entry.state_name
    );

  if mismatch_count <> 0 then
    raise exception 'geography catalog entries must match their canonical state and county jurisdictions';
  end if;
end
$$;

create or replace function property_ingest.enforce_geography_catalog_import_membership()
returns trigger
language plpgsql
set search_path = pg_catalog, property_ingest
as $$
begin
  perform property_ingest.validate_geography_catalog_import(new.id);
  return new;
end
$$;

create or replace function property_ingest.enforce_geography_catalog_entry_membership()
returns trigger
language plpgsql
set search_path = pg_catalog, property_ingest
as $$
declare
  import_id uuid;
begin
  for import_id in
    select distinct catalog_import_id from new_entries
  loop
    perform property_ingest.validate_geography_catalog_import(import_id);
  end loop;
  return null;
end
$$;

revoke all on function property_ingest.validate_geography_catalog_import(uuid)
  from public, anon, authenticated, service_role;
revoke all on function property_ingest.enforce_geography_catalog_import_membership()
  from public, anon, authenticated, service_role;
revoke all on function property_ingest.enforce_geography_catalog_entry_membership()
  from public, anon, authenticated, service_role;

create constraint trigger enforce_geography_catalog_import_membership
after insert on property_ingest.geography_catalog_imports
deferrable initially deferred
for each row execute function property_ingest.enforce_geography_catalog_import_membership();

create trigger enforce_geography_catalog_entry_membership
after insert on property_ingest.geography_catalog_entries
referencing new table as new_entries
for each statement execute function property_ingest.enforce_geography_catalog_entry_membership();

revoke all on property_ingest.geography_catalog_imports,
  property_ingest.geography_catalog_entries from public, anon, authenticated;
grant select on property_ingest.geography_catalog_imports,
  property_ingest.geography_catalog_entries to authenticated;
grant all on property_ingest.geography_catalog_imports,
  property_ingest.geography_catalog_entries to service_role;

alter table property_ingest.geography_catalog_imports enable row level security;
alter table property_ingest.geography_catalog_imports force row level security;
alter table property_ingest.geography_catalog_entries enable row level security;
alter table property_ingest.geography_catalog_entries force row level security;

-- Reference/ledger data: any authenticated user may read; only service_role
-- writes (the import module runs with a service-role connection, never an
-- ordinary user session -- unlike jurisdictions, there is no admin-console
-- use case for hand-editing an immutable ingestion ledger, so there is no
-- authenticated-admin write policy here at all).
create policy geography_catalog_imports_read
  on property_ingest.geography_catalog_imports for select to authenticated
  using (true);

create policy geography_catalog_entries_read
  on property_ingest.geography_catalog_entries for select to authenticated
  using (true);

commit;
